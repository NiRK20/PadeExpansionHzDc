def EzP21(z, theta):
    _, h0, q0, j0 = theta

    a1 = 1/h0
    a2 = (1 -2 * j0 + 2 * q0 + 3 * (q0 ** 2))/(6*h0*(1 + q0))
    b1 = (2 -j0 + 4 * q0 + 3 * (q0 ** 2))/(3*(1 + q0))

    hz = ((1 + b1 * z) ** 2) / (a1 + a2 * z * (2 + b1 * z))

    return hz/h0
    
